import { readFile, writeFile, unlink, mkdir } from 'node:fs/promises';
import { existsSync, readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createHash } from 'node:crypto';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'vite';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const PROJECT_ROOT = resolve(__dirname, '..');
const toolVersions = Object.fromEntries(['ajv', 'ajv-formats', 'vite'].map(name => [
  name, JSON.parse(readFileSync(resolve(PROJECT_ROOT, 'node_modules', name, 'package.json'), 'utf8')).version
]));
const helperLicenses = ['ajv', 'ajv-formats'].map(name =>
  `${name}:\n${readFileSync(resolve(PROJECT_ROOT, 'node_modules', name, 'LICENSE'), 'utf8').trim()}`
).join('\n\n');

export const PINNED_SETTINGS = {
  toolVersions,
  ajvOptions: {
    strict: true,
    allErrors: false,
    coerceTypes: false,
    useDefaults: false,
    removeAdditional: false,
    code: { source: true, esm: true }
  },
  exports: {
    validateReport: 'urn:google-sheets-exporter:report.schema.json',
    validateExport: 'urn:google-sheets-exporter:export.schema.json'
  },
  vite: {
    target: 'es2022',
    minify: true,
    format: 'es'
  }
};

export function canonicalJson(value) {
  if (value === null || typeof value !== 'object') {
    return JSON.stringify(value);
  }
  if (Array.isArray(value)) {
    return '[' + value.map(canonicalJson).join(',') + ']';
  }
  const keys = Object.keys(value).sort();
  return '{' + keys.map(k => `${JSON.stringify(k)}:${canonicalJson(value[k])}`).join(',') + '}';
}

export function computeSchemaHash(reportSchema, exportSchema, settings = PINNED_SETTINGS) {
  const payload = {
    reportSchema,
    exportSchema,
    settings
  };
  return createHash('sha256').update(canonicalJson(payload)).digest('hex');
}

export async function generateValidators(options = {}) {
  const root = options.projectRoot || PROJECT_ROOT;
  const outDir = options.outDir || resolve(root, 'src/contracts/generated');
  const scratchDir = options.scratchDir || resolve(root, '.local');
  const isCheckMode = Boolean(options.check);

  const reportSchemaPath = resolve(root, 'src/contracts/report.schema.json');
  const exportSchemaPath = resolve(root, 'src/contracts/export.schema.json');

  const reportSchemaRaw = await readFile(reportSchemaPath, 'utf8');
  const exportSchemaRaw = await readFile(exportSchemaPath, 'utf8');

  const reportSchema = JSON.parse(reportSchemaRaw);
  const exportSchema = JSON.parse(exportSchemaRaw);

  const hash = computeSchemaHash(reportSchema, exportSchema);

  // Compile with Ajv2020 Draft 2020-12
  const ajv = new Ajv2020(PINNED_SETTINGS.ajvOptions);
  addFormats(ajv);
  ajv.addSchema(reportSchema).addSchema(exportSchema);

  // Generate standalone ESM code
  const standaloneRaw = standaloneCode(ajv, {
    validateReport: reportSchema.$id,
    validateExport: exportSchema.$id
  });

  // Bundle standalone JS + pure runtime helpers using Vite8
  await mkdir(scratchDir, { recursive: true });
  const tempEntryId = `standalone-intermediate-${Date.now()}-${Math.random().toString(36).slice(2, 8)}.mjs`;
  const tempEntryPath = resolve(scratchDir, tempEntryId);

  let bundledCode;
  try {
    await writeFile(tempEntryPath, standaloneRaw, 'utf8');

    const result = await build({
      configFile: false,
      publicDir: false,
      logLevel: 'silent',
      build: {
        write: false,
        emptyOutDir: false,
        minify: true,
        target: 'es2022',
        lib: {
          entry: tempEntryPath,
          formats: ['es'],
          fileName: 'validators'
        }
      }
    });

    const chunks = (Array.isArray(result) ? result : [result])
      .flatMap(item => item.output)
      .filter(item => item.type === 'chunk');

    if (chunks.length !== 1 || !chunks[0].code || chunks[0].imports.length || chunks[0].dynamicImports.length) {
      throw new Error('Expected one self-contained validator chunk without imports');
    }
    bundledCode = chunks[0].code;
  } finally {
    await unlink(tempEntryPath).catch(() => {});
  }

  const jsBanner = [
    '/**',
    ' * Precompiled JSON Schema validators for report and export documents.',
    ' * Generated by scripts/generate-validators.mjs. DO NOT EDIT DIRECTLY.',
    ` * Input schema and settings hash: ${hash}`,
    ' *',
    ' * Includes bundled pure runtime helpers from Ajv and ajv-formats (MIT License).',
    ...helperLicenses.replace(/\r\n/g, '\n').split('\n').map(line => line ? ` * ${line}` : ' *'),
    ' */',
    ''
  ].join('\n');

  const finalJs = (jsBanner + bundledCode).replace(/\r\n/g, '\n').trimEnd() + '\n';

  const dtsBanner = [
    '/**',
    ' * Type declarations for precompiled JSON Schema validators.',
    ' * Generated by scripts/generate-validators.mjs. DO NOT EDIT DIRECTLY.',
    ` * Input schema and settings hash: ${hash}`,
    ' */',
    '',
    'export interface GeneratedValidator {',
    '  (data: unknown): boolean;',
    '  errors?: unknown[] | null;',
    '}',
    '',
    'export const validateReport: GeneratedValidator;',
    'export const validateExport: GeneratedValidator;',
    ''
  ].join('\n');

  const finalDts = dtsBanner.replace(/\r\n/g, '\n').trimEnd() + '\n';

  const targetJsPath = resolve(outDir, 'validators.js');
  const targetDtsPath = resolve(outDir, 'validators.d.ts');

  if (isCheckMode) {
    if (!existsSync(targetJsPath) || !existsSync(targetDtsPath)) {
      throw new Error(
        `Generated validators are missing in ${outDir}. Run "npm run schemas:generate" to create them.`
      );
    }
    const currentJs = readFileSync(targetJsPath, 'utf8').replace(/\r\n/g, '\n');
    const currentDts = readFileSync(targetDtsPath, 'utf8').replace(/\r\n/g, '\n');

    if (currentJs !== finalJs || currentDts !== finalDts) {
      throw new Error(
        `Generated validators in ${outDir} are stale. Run "npm run schemas:generate" to regenerate.`
      );
    }

    return { upToDate: true, hash };
  }

  await mkdir(outDir, { recursive: true });
  await writeFile(targetJsPath, finalJs, 'utf8');
  await writeFile(targetDtsPath, finalDts, 'utf8');

  return { written: true, hash, files: [targetJsPath, targetDtsPath] };
}

// CLI entry point
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const args = process.argv.slice(2);
  const check = args.includes('--check');

  let outDirIndex = args.indexOf('--out-dir');
  let outDir;
  if (outDirIndex !== -1 && args[outDirIndex + 1]) {
    outDir = resolve(args[outDirIndex + 1]);
  }

  try {
    const result = await generateValidators({ check, outDir });
    if (check) {
      process.stdout.write(`Validators are up-to-date (hash: ${result.hash.slice(0, 16)}).\n`);
    } else {
      process.stdout.write(
        `Generated validators successfully (hash: ${result.hash.slice(0, 16)}).\n`
      );
    }
    process.exit(0);
  } catch (error) {
    process.stderr.write(`Schema validator check/generate failed: ${error.message}\n`);
    process.exit(1);
  }
}
